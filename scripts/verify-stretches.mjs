import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => { errors.push(String(e)); console.error(e) })
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5175')
  // Deterministic analysis fixture: exercise the actual Moments component and
  // context navigation without waiting for engine estimates to produce episodes.
  await page.evaluate(async () => { const { mountFixture } = await import('/scripts/stretches-fixture.jsx'); mountFixture() })
  const rows = page.locator('.stretch-row')
  await rows.first().waitFor()
  assert.equal(await rows.count(), 3)
  await rows.first().click()
  assert.equal(await page.locator('.stretch-detail').count(), 1)
  assert.equal(await page.locator('.timeline-scroll [aria-pressed=true]').count(), 1)
  await page.getByRole('button', { name: 'Review stretch', exact: true }).click()
  await page.getByRole('button', { name: 'Previous stretch move' }).isDisabled().then(assert)
  for (let ply = 1; ply <= 5; ply++) {
    await page.getByRole('button', { name: 'Next stretch move' }).click()
    assert.match(await page.locator('#board-position').innerText(), new RegExp(`^${ply}:`))
  }
  assert.match(await page.locator('.stretch-playback [role=status]').innerText(), /End of stretch/)
  assert(await page.getByRole('button', { name: 'Next stretch move' }).isDisabled())
  await page.getByRole('button', { name: 'Previous stretch move' }).click()
  assert.match(await page.locator('#board-position').innerText(), /^4:/)
  await page.locator('.stretch-finding').first().click()
  assert.match(await page.locator('#board-position').innerText(), /^4:/)
  await page.getByText('More board changes (1)', { exact: true }).click()
  assert.equal(await page.locator('.stretch-finding:visible').count(), 2)
  await page.getByRole('button', { name: 'Black narrowing stretch, moves 1 to 3', exact: true }).focus()
  await page.keyboard.press('Enter')
  assert.equal(await page.locator('.stretch-detail').count(), 1)
  assert.match(await page.locator('.stretch-detail h3').innerText(), /Black/)
  assert.match(await page.locator('#board-position').innerText(), /^1:/)
  await page.getByLabel('Ends near one choice').check()
  assert.equal(await rows.count(), 2)
  assert.equal(await page.locator('.stretch-detail').count(), 0)
  await page.getByLabel('Player filter fixture').selectOption('black')
  assert.equal(await rows.count(), 0)
  assert.match(await page.locator('.stretch-empty').innerText(), /No stretches end near one choice/)
  await page.getByLabel('Ends near one choice').uncheck()
  assert.equal(await rows.count(), 1)
  await page.getByLabel('Player filter fixture').selectOption('both')
  await rows.last().click()
  assert.match(await page.locator('.stretch-findings').innerText(), /No structural change/)
  await fs.mkdir('artifacts/ui-audit/stretches', { recursive: true })
  await page.screenshot({ path: 'artifacts/ui-audit/stretches/desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'artifacts/ui-audit/stretches/mobile.png', fullPage: true })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No mobile overflow')
  const bounds = await page.locator('.stretch-explorer').boundingBox()
  assert(bounds.x >= 0 && bounds.x + bounds.width <= 390, 'Explorer is inside mobile viewport')
  assert.deepEqual(errors, [])
  console.log('PASS interval selection, single expansion, playback including replies and endpoint, findings, filters, empty states, keyboard, mobile overflow')
} finally { await browser.close() }
